using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.Globalization;
using System.Linq;
using Avalonia;
using Avalonia.Input;
using Avalonia.Media;
using Avalonia.Threading;
using Arc.Avalonia.Theme;

namespace Arc.Avalonia.Charts;

/// <summary>
/// A rolling live stream: a fixed time window of one or more series that slides as samples arrive, a live
/// pulse in the corner, and a pause that freezes the view so a point can be read. The newest reading is
/// drawn one interval behind the right edge, so points slide in instead of popping.
/// </summary>
/// <remarks>
/// Approximation: there is no socket here. Samples that arrive while live are generated by a fixed seed
/// around the seed series' mean, so the control looks alive on its own and renders identically in a
/// screenshot. Feed live readings by resetting <see cref="Values"/> or <see cref="Series"/> from a timer
/// in the host view. With <see cref="ArcThemeManager.ReducedMotion"/> on, the stream does not scroll: it
/// redraws only when data changes.
/// </remarks>
public class ArcRealtimeStream : ArcChartBase
{
    public static readonly StyledProperty<IReadOnlyList<ChartSeries>?> SeriesProperty =
        AvaloniaProperty.Register<ArcRealtimeStream, IReadOnlyList<ChartSeries>?>(nameof(Series));

    public static readonly StyledProperty<IReadOnlyList<double>?> ValuesProperty =
        AvaloniaProperty.Register<ArcRealtimeStream, IReadOnlyList<double>?>(nameof(Values));

    public static readonly StyledProperty<int> WindowSizeProperty =
        AvaloniaProperty.Register<ArcRealtimeStream, int>(nameof(WindowSize), 36);

    public static readonly StyledProperty<TimeSpan> IntervalProperty =
        AvaloniaProperty.Register<ArcRealtimeStream, TimeSpan>(nameof(Interval), TimeSpan.FromMilliseconds(500));

    public static readonly StyledProperty<bool> IsLiveProperty =
        AvaloniaProperty.Register<ArcRealtimeStream, bool>(nameof(IsLive), true);

    public static readonly StyledProperty<string?> ValueSuffixProperty =
        AvaloniaProperty.Register<ArcRealtimeStream, string?>(nameof(ValueSuffix));

    public static readonly StyledProperty<Func<double, string>?> ValueFormatProperty =
        AvaloniaProperty.Register<ArcRealtimeStream, Func<double, string>?>(nameof(ValueFormat));

    private static readonly CultureInfo Culture = CultureInfo.InvariantCulture;

    private readonly Random _random = new(20260214);
    private List<ChartSeries> _defs = new();
    private List<List<double>> _buffers = new();
    private double[] _baselines = Array.Empty<double>();
    private DispatcherTimer? _timer;
    private Stopwatch? _watch;
    private double _lastTick;
    private double _phase;
    private double _pulse = 0.6;
    private int _step;
    private Rect _plot;
    private Rect _pill;
    private bool _pillHover;
    private bool _keyboardFocus;
    private int _hoverIndex = -1;

    static ArcRealtimeStream()
    {
        AffectsRender<ArcRealtimeStream>(
            SeriesProperty,
            ValuesProperty,
            WindowSizeProperty,
            IntervalProperty,
            IsLiveProperty,
            ValueSuffixProperty,
            ValueFormatProperty);
        SeriesProperty.Changed.AddClassHandler<ArcRealtimeStream>((stream, _) => stream.ResetData());
        ValuesProperty.Changed.AddClassHandler<ArcRealtimeStream>((stream, _) => stream.ResetData());
        WindowSizeProperty.Changed.AddClassHandler<ArcRealtimeStream>((stream, _) => stream.ResetData());
        IsLiveProperty.Changed.AddClassHandler<ArcRealtimeStream>((stream, _) => stream.SyncTimer());
    }

    public ArcRealtimeStream()
    {
        Focusable = true;
        EnsureData();
    }

    /// <summary>Series to stream. Each series seeds its own rolling buffer from the values given.</summary>
    public IReadOnlyList<ChartSeries>? Series
    {
        get => GetValue(SeriesProperty);
        set => SetValue(SeriesProperty, value);
    }

    /// <summary>A single series, as a shortcut for one measure.</summary>
    public IReadOnlyList<double>? Values
    {
        get => GetValue(ValuesProperty);
        set => SetValue(ValuesProperty, value);
    }

    /// <summary>Number of samples kept in the visible window.</summary>
    public int WindowSize
    {
        get => GetValue(WindowSizeProperty);
        set => SetValue(WindowSizeProperty, value);
    }

    /// <summary>Expected time between samples; the view trails the newest sample by one interval.</summary>
    public TimeSpan Interval
    {
        get => GetValue(IntervalProperty);
        set => SetValue(IntervalProperty, value);
    }

    /// <summary>Whether the stream is scrolling. Space or the status pill toggles it.</summary>
    public bool IsLive
    {
        get => GetValue(IsLiveProperty);
        set => SetValue(IsLiveProperty, value);
    }

    /// <summary>Unit after values, such as "ms".</summary>
    public string? ValueSuffix
    {
        get => GetValue(ValueSuffixProperty);
        set => SetValue(ValueSuffixProperty, value);
    }

    /// <summary>Formats values in the readout and the tooltip.</summary>
    public Func<double, string>? ValueFormat
    {
        get => GetValue(ValueFormatProperty);
        set => SetValue(ValueFormatProperty, value);
    }

    protected override double DefaultHeight => 244;

    /// <summary>Holds the view where it is and stops appending samples.</summary>
    public void Pause() => SetCurrentValue(IsLiveProperty, false);

    /// <summary>Resumes scrolling from the current window.</summary>
    public void Resume() => SetCurrentValue(IsLiveProperty, true);

    protected override void OnAttachedToVisualTree(VisualTreeAttachmentEventArgs e)
    {
        base.OnAttachedToVisualTree(e);
        if (_buffers.Count == 0)
        {
            EnsureData();
        }

        SyncTimer();
        InvalidateVisual();
    }

    protected override void OnDetachedFromVisualTree(VisualTreeAttachmentEventArgs e)
    {
        base.OnDetachedFromVisualTree(e);
        StopTimer();
    }

    protected override void OnPointerMoved(PointerEventArgs e)
    {
        base.OnPointerMoved(e);
        var point = e.GetPosition(this);

        var overPill = _pill.Contains(point);
        if (overPill != _pillHover)
        {
            _pillHover = overPill;
            InvalidateVisual();
        }

        Cursor = overPill ? new Cursor(StandardCursorType.Hand) : null;
        _hoverIndex = IndexAt(point);
        InvalidateVisual();
    }

    protected override void OnPointerExited(PointerEventArgs e)
    {
        base.OnPointerExited(e);
        _pillHover = false;
        _hoverIndex = -1;
        Cursor = null;
        InvalidateVisual();
    }

    protected override void OnPointerPressed(PointerPressedEventArgs e)
    {
        base.OnPointerPressed(e);
        Focus();
        if (_keyboardFocus)
        {
            _keyboardFocus = false;
            InvalidateVisual();
        }

        if (_pill.Contains(e.GetPosition(this)))
        {
            SetCurrentValue(IsLiveProperty, !IsLive);
            e.Handled = true;
        }
    }

    protected override void OnKeyDown(KeyEventArgs e)
    {
        base.OnKeyDown(e);
        if (_buffers.Count == 0)
        {
            return;
        }

        if (!_keyboardFocus)
        {
            _keyboardFocus = true;
            InvalidateVisual();
        }

        var count = SampleCount();
        var next = _hoverIndex < 0 ? count - 1 : _hoverIndex;
        switch (e.Key)
        {
            case Key.Left:
                next = Math.Max(0, next - 1);
                break;
            case Key.PageUp:
                next = Math.Max(0, next - 10);
                break;
            case Key.Right:
                next = Math.Min(count - 1, next + 1);
                break;
            case Key.PageDown:
                next = Math.Min(count - 1, next + 10);
                break;
            case Key.Home:
                next = 0;
                break;
            case Key.End:
                next = count - 1;
                break;
            case Key.Space:
            case Key.Enter:
                SetCurrentValue(IsLiveProperty, !IsLive);
                e.Handled = true;
                return;
            case Key.Escape:
                _hoverIndex = -1;
                SetCurrentValue(IsLiveProperty, true);
                InvalidateVisual();
                e.Handled = true;
                return;
            default:
                return;
        }

        _hoverIndex = next;
        InvalidateVisual();
        e.Handled = true;
    }

    public override void Render(DrawingContext context)
    {
        base.Render(context);
        if (_buffers.Count == 0 || _buffers[0].Count == 0)
        {
            EnsureData();
        }

        if (_buffers.Count == 0 || _buffers[0].Count == 0)
        {
            ChartText.Draw(
                context,
                "Waiting for data",
                Bounds.Width / 2,
                Bounds.Height / 2,
                13,
                ChartPalette.Muted,
                alignment: TextAlignment.Center);
            return;
        }

        _plot = new Rect(8, 30, Math.Max(20, Bounds.Width - 8 - 44), Math.Max(20, Bounds.Height - 30 - 22));
        if (_plot.Width < 30 || _plot.Height < 30)
        {
            return;
        }

        var interval = Math.Max(0.05, Interval.TotalSeconds);
        var span = Math.Max(1, WindowSize) * interval;
        var low = double.MaxValue;
        var high = double.MinValue;
        for (var series = 0; series < _buffers.Count; series++)
        {
            foreach (var value in _buffers[series])
            {
                low = Math.Min(low, value);
                high = Math.Max(high, value);
            }
        }

        if (low is double.MaxValue || high <= low)
        {
            low = 0;
            high = 1;
        }

        var padding = Math.Max(1, (high - low) * 0.18);
        low = Math.Max(0, low - padding);
        high += padding;

        // Grid and value labels.
        var gridPen = new Pen(ChartPalette.BorderSubtle, 1);
        for (var tick = 0; tick <= 3; tick++)
        {
            var value = low + (high - low) * tick / 3;
            var y = Crisp(ValueY(value, low, high));
            context.DrawLine(gridPen, new Point(_plot.Left, y), new Point(_plot.Right, y));
            ChartText.Draw(
                context,
                high - low >= 20 ? ChartFormat.Compact(Math.Round(value)) : ChartFormat.Number(value, 1),
                _plot.Right + 7,
                y,
                11,
                ChartPalette.Muted);
        }

        // Time axis: relative offsets from now.
        for (var tick = 0; tick <= 3; tick++)
        {
            var offset = -span * (3 - tick) / 3;
            var x = _plot.Right + offset / span * _plot.Width;
            ChartText.Draw(
                context,
                FormatOffset(offset),
                x,
                _plot.Bottom + 11,
                11,
                ChartPalette.Muted,
                alignment: tick == 3 ? TextAlignment.Right : tick == 0 ? TextAlignment.Left : TextAlignment.Center);
        }

        var sampleCount = SampleCount();
        using (context.PushClip(new Rect(_plot.Left - 1, _plot.Top - 8, _plot.Width + 2, _plot.Height + 10)))
        {
            for (var series = 0; series < _buffers.Count; series++)
            {
                var brush = BrushFor(series);
                var points = new List<Point>(sampleCount);
                var values = _buffers[series];
                for (var index = 0; index < values.Count; index++)
                {
                    var age = values.Count - 1 - index - _phase;
                    var x = _plot.Right + (-age * interval) / span * _plot.Width;
                    if (x < _plot.Left - 8)
                    {
                        continue;
                    }

                    points.Add(new Point(x, ValueY(values[index], low, high)));
                }

                if (points.Count < 2)
                {
                    continue;
                }

                context.DrawGeometry(
                    ChartPalette.Alpha(brush, 0.09),
                    null,
                    ChartGeometry.Area(points, _plot.Bottom, true));
                context.DrawGeometry(null, ChartPalette.Pen(brush, 1.75), ChartGeometry.Line(points, true));
                var head = points[^1];
                context.DrawEllipse(ChartPalette.Surface, null, head, 4, 4);
                context.DrawEllipse(brush, null, head, 2.6, 2.6);
            }
        }

        DrawReadingRow(context);
        DrawStatusPill(context);
        DrawHover(context, span, low, high);

        if (_keyboardFocus && IsFocused)
        {
            context.DrawRectangle(
                null,
                new Pen(ArcResources.Brush(ArcTokens.FocusOutline), 2),
                new RoundedRect(
                    new Rect(1.5, 1.5, Math.Max(0, Bounds.Width - 3), Math.Max(0, Bounds.Height - 3)),
                    12));
        }
    }

    private void DrawReadingRow(DrawingContext context)
    {
        var x = 2.0;
        var centerY = 13.0;
        var pillLeft = Bounds.Width - 86;
        for (var series = 0; series < _defs.Count && series < _buffers.Count; series++)
        {
            if (_buffers[series].Count == 0)
            {
                continue;
            }

            var brush = BrushFor(series);
            var name = _defs[series].Name;
            var value = FormatValue(_buffers[series][^1]);
            var nameText = ChartText.Create(name, 11, ChartPalette.Muted, maxWidth: 90);
            var valueText = ChartText.Create(value, 13, ChartPalette.Foreground, FontWeight.Medium);
            var width = 8 + 5 + nameText.Width + 5 + valueText.Width + 16;
            if (x + width > pillLeft)
            {
                break;
            }

            context.DrawEllipse(brush, null, new Point(x + 3, centerY), 3, 3);
            context.DrawText(nameText, new Point(x + 11, centerY - nameText.Height / 2));
            context.DrawText(valueText, new Point(x + 11 + nameText.Width + 5, centerY - valueText.Height / 2));
            x += width;
        }
    }

    private void DrawStatusPill(DrawingContext context)
    {
        var live = IsLive;
        var width = live ? 62.0 : 78.0;
        _pill = new Rect(Bounds.Width - width - 2, 3, width, 20);
        context.DrawRectangle(
            _pillHover ? ChartPalette.Alpha(ChartPalette.BorderSubtle, 0.9) : ChartPalette.Surface,
            new Pen(ChartPalette.Border, 1),
            new RoundedRect(_pill, 10));

        var centerY = _pill.Center.Y;
        if (live && !ArcThemeManager.ReducedMotion)
        {
            var pulse = 0.5 + 0.5 * Math.Sin(_pulse * Math.PI * 2);
            context.DrawEllipse(
                ChartPalette.Alpha(ChartPalette.Series(0), 0.18 * (1 - pulse) + 0.06),
                null,
                new Point(_pill.X + 12, centerY),
                3.2 + 3.4 * pulse,
                3.2 + 3.4 * pulse);
        }

        context.DrawEllipse(
            live ? ChartPalette.Series(0) : ChartPalette.Muted,
            null,
            new Point(_pill.X + 12, centerY),
            3.2,
            3.2);
        ChartText.Draw(
            context,
            live ? "Live" : "Paused",
            _pill.X + 20,
            centerY,
            11,
            live ? ChartPalette.Secondary : ChartPalette.Muted,
            FontWeight.Medium);
    }

    private void DrawHover(DrawingContext context, double span, double low, double high)
    {
        if (_hoverIndex < 0 || _buffers.Count == 0)
        {
            return;
        }

        var interval = Math.Max(0.05, Interval.TotalSeconds);
        var age = _buffers[0].Count - 1 - _hoverIndex - _phase;
        var x = _plot.Right + (-age * interval) / span * _plot.Width;
        if (x < _plot.Left || x > _plot.Right)
        {
            return;
        }

        x = Math.Round(x) + 0.5;
        context.DrawLine(
            new Pen(ChartPalette.BorderStrong, 1, new DashStyle(new[] { 3.0, 3.0 }, 0)),
            new Point(x, _plot.Top),
            new Point(x, _plot.Bottom));

        var rows = new List<(string Label, string Value, IBrush? Brush)>();
        for (var series = 0; series < _buffers.Count; series++)
        {
            if (_hoverIndex >= _buffers[series].Count)
            {
                continue;
            }

            var value = _buffers[series][_hoverIndex];
            rows.Add((_defs[series].Name, FormatValue(value), BrushFor(series)));
            context.DrawEllipse(
                ChartPalette.Surface,
                null,
                new Point(x, ValueY(value, low, high)),
                4,
                4);
            context.DrawEllipse(BrushFor(series), null, new Point(x, ValueY(value, low, high)), 2.6, 2.6);
        }

        var offsetSeconds = -age * interval;
        ChartTooltip.Draw(
            context,
            Bounds,
            new Point(x, _plot.Top + 24),
            FormatOffset(offsetSeconds) + " from now",
            rows);
    }

    private void EnsureData()
    {
        var series = Series;
        var values = Values;
        var defs = new List<ChartSeries>();
        if (series is { Count: > 0 })
        {
            defs.AddRange(series);
        }
        else if (values is { Count: > 0 })
        {
            defs.Add(new ChartSeries("Value", values));
        }
        else
        {
            defs.Add(new ChartSeries("Value", Array.Empty<double>()));
        }

        _defs = defs;
        _buffers = new List<List<double>>(defs.Count);
        _baselines = new double[defs.Count];
        _phase = 0;
        var window = Math.Max(4, WindowSize);
        for (var index = 0; index < defs.Count; index++)
        {
            var seed = defs[index].Values;
            var buffer = new List<double>(window + 2);
            if (seed.Count > 0)
            {
                var start = Math.Max(0, seed.Count - window);
                var tail = new List<double>(window);
                for (var at = start; at < seed.Count; at++)
                {
                    tail.Add(Math.Max(0, seed[at]));
                }

                _baselines[index] = Math.Max(1, tail.Average());
                // The seed is the newest stretch of the feed; fill the earlier window around its mean.
                for (var at = tail.Count; at < window; at++)
                {
                    buffer.Add(NextSample(index));
                }

                buffer.AddRange(tail);
            }
            else
            {
                _baselines[index] = 120 + index * 55;
                for (var at = 0; at < window; at++)
                {
                    buffer.Add(NextSample(index));
                }
            }

            _buffers.Add(buffer);
        }
    }

    private double NextSample(int series)
    {
        _step++;
        var baseline = Math.Max(1, _baselines[series]);
        var wave = baseline * 0.20 * Math.Sin(_step * 0.34 + series * 1.9);
        var drift = baseline * 0.10 * Math.Sin(_step * 0.09 + series * 0.7);
        var jitter = (_random.NextDouble() - 0.5) * baseline * 0.16;
        return Math.Max(0, baseline + wave + drift + jitter);
    }

    private void AppendSample()
    {
        var window = Math.Max(4, WindowSize);
        for (var index = 0; index < _buffers.Count; index++)
        {
            var buffer = _buffers[index];
            buffer.Add(NextSample(index));
            while (buffer.Count > window + 2)
            {
                buffer.RemoveAt(0);
            }
        }
    }

    private void ResetData()
    {
        EnsureData();
        InvalidateVisual();
    }

    private void SyncTimer()
    {
        if (IsLive && !ArcThemeManager.ReducedMotion && VisualRoot is not null)
        {
            StartTimer();
        }
        else
        {
            StopTimer();
        }

        InvalidateVisual();
    }

    private void StartTimer()
    {
        if (_timer is not null)
        {
            return;
        }

        _watch = Stopwatch.StartNew();
        _lastTick = 0;
        _timer = new DispatcherTimer { Interval = TimeSpan.FromMilliseconds(16) };
        _timer.Tick += (_, _) => OnTick();
        _timer.Start();
    }

    private void OnTick()
    {
        if (_watch is null)
        {
            return;
        }

        var now = _watch.Elapsed.TotalMilliseconds;
        var delta = Math.Clamp(now - _lastTick, 1, 120);
        _lastTick = now;
        var interval = Math.Max(50, Interval.TotalMilliseconds);
        _phase += delta / interval;
        _pulse = (_pulse + delta / 1600.0) % 1;
        var guard = 0;
        while (_phase >= 1 && guard++ < 4)
        {
            _phase -= 1;
            AppendSample();
        }

        InvalidateVisual();
    }

    private void StopTimer()
    {
        _timer?.Stop();
        _timer = null;
        _watch = null;
        _lastTick = 0;
        _phase = 0;
    }

    private int SampleCount() => _buffers.Count == 0 ? 0 : _buffers[0].Count;

    private int IndexAt(Point point)
    {
        if (!_plot.Contains(point) || _buffers.Count == 0)
        {
            return -1;
        }

        var interval = Math.Max(0.05, Interval.TotalSeconds);
        var span = Math.Max(1, WindowSize) * interval;
        var offset = (point.X - _plot.Right) / _plot.Width * span;
        var age = -offset / interval + _phase;
        var index = _buffers[0].Count - 1 - (int)Math.Round(age);
        return Math.Clamp(index, 0, _buffers[0].Count - 1);
    }

    private IBrush BrushFor(int series)
        => series < _defs.Count
            ? _defs[series].Brush ?? ChartPalette.Series(series)
            : ChartPalette.Series(series);

    private double ValueY(double value, double low, double high)
        => _plot.Bottom - (value - low) / Math.Max(1e-6, high - low) * _plot.Height;

    private string FormatOffset(double seconds)
    {
        if (Math.Abs(seconds) < 0.6)
        {
            return "now";
        }

        var magnitude = Math.Abs(seconds);
        var text = magnitude >= 120
            ? (magnitude / 60).ToString("0", Culture) + "m"
            : Math.Round(magnitude).ToString("0", Culture) + "s";
        return "-" + text;
    }

    private string FormatValue(double value)
    {
        var formatted = ValueFormat?.Invoke(value) ?? ChartFormat.Number(value, 0);
        return string.IsNullOrEmpty(ValueSuffix) ? formatted : formatted + ValueSuffix;
    }
}
